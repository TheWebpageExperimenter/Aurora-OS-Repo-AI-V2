#!/usr/bin/env python3
"""Generate Aurora's freestanding, antialiased glyph atlas from a TrueType font.
Requires Pillow only when regenerating kernel/font_ttf.h; normal kernel builds do not.
"""
from PIL import Image, ImageDraw, ImageFont
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
font_path = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'assets/fonts/SegoeUI.ttf'
# bitmap columns and line-height; every 4-pixel group is packed as 2-bit coverage
specs = [
    ('s', 12, 16, 16),
    ('m', 16, 24, 20),
    ('l', 24, 28, 30),
]
chars = list(range(32, 127))
out = ['/* Generated by tools/ttf2c.py from the selected TrueType font. */', '#pragma once', '#include <stdint.h>', '']
for tag, px, max_w, max_h in specs:
    font = ImageFont.truetype(str(font_path), px)
    ascent, descent = font.getmetrics()
    line_h = ascent + descent
    out.append(f'#define TTF_{tag.upper()}_W {max_w}')
    out.append(f'#define TTF_{tag.upper()}_H {max_h}')
    out.append(f'#define TTF_{tag.upper()}_LINE_H {line_h}')
    out.append(f'static const uint8_t ttf_{tag}_adv[95] = {{')
    adv = [max(1, int(font.getlength(chr(c)) + 0.5)) for c in chars]
    for i in range(0, len(adv), 16):
        out.append('    ' + ', '.join(map(str, adv[i:i+16])) + ',')
    out.append('};')
    raw = []
    # each glyph uses a fixed-size cell; glyphs share a baseline for natural line alignment
    for code in chars:
        ch = chr(code)
        im = Image.new('L', (max_w, max_h), 0)
        dr = ImageDraw.Draw(im)
        dr.text((0, ascent), ch, font=font, fill=255, anchor='ls', stroke_width=0)
        # Four coverage levels make the embedded font compact while preserving antialiasing.
        pix = [0 if v < 48 else 1 if v < 128 else 2 if v < 208 else 3 for v in im.getdata()]
        if len(pix) % 4:
            pix += [0] * (4 - len(pix) % 4)
        packed = [(pix[i] << 6) | (pix[i+1] << 4) | (pix[i+2] << 2) | pix[i+3]
                  for i in range(0, len(pix), 4)]
        raw.extend(packed)
    per_glyph = max_w * max_h // 4
    out.append(f'#define TTF_{tag.upper()}_BYTES_PER_GLYPH {per_glyph}')
    out.append(f'static const uint8_t ttf_{tag}_bitmap[95][{per_glyph}] = {{')
    for g in range(95):
        vals = raw[g*per_glyph:(g+1)*per_glyph]
        out.append('    {' + ','.join(f'0x{v:02x}' for v in vals) + '},')
    out.append('};\n')
(root / 'kernel/font_ttf.h').write_text('\n'.join(out) + '\n')
print(f'generated {root / "kernel/font_ttf.h"} from {font_path}')
